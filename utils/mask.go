package utils

import "strings"

// MaskTel ปิดบังเบอร์โทรสำหรับเขียนลง log
//
// log ของระบบนี้ไหลออกไปที่ stdout ของ container แล้วเข้า log stream
// ซึ่งมีคนอ่านได้กว้างกว่าฐานข้อมูลมาก และไม่มี retention policy
// เบอร์โทรลูกค้าไม่ควรอยู่ในนั้นแบบเต็มหมายเลข
//
// เก็บสามตัวหน้ากับสามตัวท้ายไว้ เพื่อให้ยังเทียบกับรายการในฐานข้อมูลได้
// เวลาไล่ปัญหา แต่ไม่พอจะเอาไปติดต่อลูกค้า
//
//	0925359415 -> 092xxxx415
//	0000000000 -> 0000000000   (ไม่ระบุตัวตน ไม่ใช่ข้อมูลส่วนบุคคล)
//	""         -> (ไม่ระบุ)
func MaskTel(tel string) string {
	t := strings.TrimSpace(tel)

	if t == "" {
		return "(ไม่ระบุ)"
	}
	// เบอร์ตัวแทนของลูกค้าทั่วไปที่ไม่ได้เป็นสมาชิก ไม่ต้องปิดบัง
	if t == "0000000000" {
		return t
	}
	// สั้นเกินกว่าจะปิดบังแล้วยังมีประโยชน์ — ปิดทั้งหมด
	if len([]rune(t)) < 7 {
		return strings.Repeat("x", len([]rune(t)))
	}

	r := []rune(t)
	return string(r[:3]) + strings.Repeat("x", len(r)-6) + string(r[len(r)-3:])
}
